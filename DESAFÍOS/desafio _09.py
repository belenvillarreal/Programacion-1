# Desafío 1: Saludo Personalizado
# Este programa solicita al usuario su nombre y su ciudad de origen,
# luego muestra un saludo personalizado utilizando la información ingresada.

print("Desafío 1: Saludo Personalizado")

# Solicitar al usuario que ingrese su nombre
nombre = input("Ingrese su nombre: ")

# Solicitar al usuario que ingrese su ciudad de origen
ciudad = input("Ingrese su ciudad de origen: ")

# Dejar una línea en blanco para mejorar la presentación
print()

# Mostrar un saludo personalizado con la información ingresada
print("¡Hola", nombre + "!")
print("Es un gusto saber que eres de", ciudad + ".")
