# Solicita al usuario una temperatura en grados Celsius
celsius = float (input ("Ingrese la temperatura en grados Celcius: "))
# Convierte la temperatura a Fahrenheit
Conversión_a_fahrenheit = (celsius * 9/5) + 32
# Convierte la temperatura a Kelvin
Conversión_a_kelvin = (celsius + 273.15)
# Muestra los resultados obtenidos
print ("Temperatura en Fahrenheit:", Conversión_a_fahrenheit)
print ("Temperatura en kelvin:", Conversión_a_kelvin)
